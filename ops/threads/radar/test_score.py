    ("Сделаю сайт под ключ за 30 тысяч, пишите", ""),
    ("Я веб-дизайнер, создаю сайты на Тильде, нужен сайт? Пишите", ""),
    ("Ветка саморекламы! Я делаю сайты для бизнеса", ""),
